// Bundle src/index.js into one ES module (dist/qelm.js) so CDNs serve a single request.
// The core modules do not import each other, so concatenation is enough; this script
// checks that assumption and fails on clashing top-level names.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');

export function bundle() {
  const { version } = JSON.parse(read('package.json'));
  const modules = [...read('src/index.js').matchAll(/^export \* from '\.\/(.+\.js)';$/gm)].map(m => m[1]);
  const seen = new Map();
  const parts = modules.map(name => {
    const source = read(`src/${name}`);
    if (/^\s*import\s/m.test(source)) throw new Error(`src/${name} has imports; extend the build script`);
    for (const [, id] of source.matchAll(/^(?:export\s+)?(?:async\s+)?(?:function\*?|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm)) {
      if (seen.has(id)) throw new Error(`top-level name ${id} in src/${name} clashes with src/${seen.get(id)}`);
      seen.set(id, name);
    }
    return `// ---- src/${name}\n${source.trimEnd()}\n`;
  });
  return `// qelm-lab ${version} — generated by scripts/build.mjs from src/; do not edit.\n${parts.join('\n')}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('dist/qelm.js', root), bundle());
  console.log('wrote dist/qelm.js');
}
